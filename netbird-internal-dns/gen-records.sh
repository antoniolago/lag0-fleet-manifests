#!/usr/bin/env bash
# Regenerates records.txt from the ton-cluster istio gateway (source of truth).
#
# The internal view of *.lag0.com.br is: every host the ton-cluster gateway
# serves resolves to the internal VIP (istio-ton = 192.168.88.190). Exceptions
# are explicit below and must stay documented in README.md.
set -euo pipefail
cd "$(dirname "$0")"
KUBECTL_CTX=${KUBECTL_CTX:-admin@ton-cluster}

{
  echo "# generated by gen-records.sh from the ${KUBECTL_CTX} istio gateway - do not edit by hand"
  echo "# format: <hostname> <cname target>"
  kubectl --context "$KUBECTL_CTX" get virtualservices.networking.istio.io -A -o json \
    | python3 -c '
import json, sys
d = json.load(sys.stdin)
hosts = set()
for item in d["items"]:
    for h in item["spec"].get("hosts") or []:
        hosts.add(h.rstrip("."))
for h in sorted(hosts):
    if h == "nb.lag0.com.br":
        continue          # stays public: it is the management URL for peer enrollment
    if h == "grafana.lag0.com.br":
        print(h, "istio-oke.lag0.com.br")   # grafana lives in OKE, not in the ton-cluster
        continue
    print(h, "istio-ton.lag0.com.br")
'
} > records.txt

echo "records.txt: $(grep -vc '^#' records.txt) records"
