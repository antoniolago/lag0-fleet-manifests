#!/usr/bin/env python3
"""Reconcile the internal DNS view of *.lag0.com.br on the MikroTik (hAP ax2).

Why the MikroTik: the hairpin DNS of the house lives there. Technitium (the
mesh resolver, 100.82.25.208 / 192.168.88.191) keeps a conditional forwarder
zone `lag0.com.br -> 192.168.88.1`, so whatever the router answers is what the
LAN **and** every NetBird peer sees. Public names that the router does not
override keep going to Cloudflare untouched (MX, TXT, apex, harbor, nb...).

What this script does: reads records.txt (generated by gen-records.sh from the
ton-cluster istio gateway) and makes the router's static DNS match it —
creating, updating and deleting only the records it manages.

  records.txt : "<hostname> <cname target>"

Credentials: the MikroTik login is a personal Vaultwarden item, reached with
the API key stored in the `vaultwarden-sync-secrets` Secret. Nothing sensitive
is printed.

Usage:
  sync.py              # dry-run: show the diff only
  sync.py --apply      # apply, then flush the router's DNS cache
  sync.py --list       # print the router's current static records
"""
import base64
import hashlib
import hmac
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

BASE = os.environ.get("BW_URL", "https://vw.lag0.com.br")
KUBE_CTX = os.environ.get("BW_KUBE_CONTEXT", "oci-lag0")
NS = "vaultwarden-kubernetes-secrets"
SECRET = os.environ.get("BW_K8S_SECRET", "vaultwarden-sync-secrets")
MIKROTIK = os.environ.get("MIKROTIK_URL", "http://192.168.88.1")
DEV = os.environ.get("BW_DEVICE_ID", "netbird-internal-dns-sync")
HERE = Path(__file__).resolve().parent

_OPENER = urllib.request.build_opener()
_OPENER.addheaders = [
    ("User-Agent", "Bitwarden_Desktop/2025.1.0"),
    ("Bitwarden-Client-Version", "2025.1.0"),
]
urllib.request.install_opener(_OPENER)


def secret(key):
    out = subprocess.run(
        ["kubectl", "--context", KUBE_CTX, "-n", NS, "get", "secret", SECRET,
         "-o", "jsonpath={.data.%s}" % key], capture_output=True, text=True)
    if out.returncode != 0 or not out.stdout.strip():
        raise SystemExit("kubernetes secret %s/%s key %s unavailable" % (NS, SECRET, key))
    return base64.b64decode(out.stdout).decode()


def b64d(s):
    s = (s or "").strip()
    return base64.b64decode(s + "=" * (-len(s) % 4)) if s else b""


def hkdf_expand(key, info, length):
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(key, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:length]


def dec(enc_str, enc_key, mac_key=None):
    """Bitwarden EncString: '[type.]iv|ct[|mac]'."""
    if not enc_str:
        return None
    typ, m = None, re.match(r"^(\d+)\.", enc_str)
    if m:
        typ = int(m.group(1))
        enc_str = enc_str[m.end():]
    if typ == 1:
        return enc_str.encode()
    parts = enc_str.split("|")
    if len(parts) not in (2, 3):
        return None
    try:
        iv, ct = b64d(parts[0]), b64d(parts[1])
        if len(parts) == 3 and mac_key is not None:
            if not hmac.compare_digest(b64d(parts[2]),
                                       hmac.new(mac_key, iv + ct, hashlib.sha256).digest()):
                return None
        c = Cipher(algorithms.AES(enc_key), modes.CBC(iv)).decryptor()
        out = c.update(ct) + c.finalize()
        return out[:-out[-1]] if out else None
    except Exception:
        return None


def to_str(b):
    if not b:
        return None
    try:
        return b.decode()
    except Exception:
        return None


def vw_token():
    body = urllib.parse.urlencode({
        "grant_type": "client_credentials",
        "client_id": secret("BW_CLIENTID"),
        "client_secret": secret("BW_CLIENTSECRET"),
        "scope": "api",
        "device_type": "6",
        "device_identifier": DEV,
        "device_name": DEV,
    }).encode()
    req = urllib.request.Request(BASE + "/identity/connect/token", data=body)
    req.add_header("Content-Type", "application/x-www-form-urlencoded")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)["access_token"]


def user_key(profile):
    email = (profile.get("email") or "").lower()
    pre = {}
    try:
        req = urllib.request.Request(BASE + "/api/accounts/prelogin",
                                     data=json.dumps({"email": email}).encode())
        req.add_header("Content-Type", "application/json")
        with urllib.request.urlopen(req, timeout=30) as r:
            pre = json.load(r)
    except Exception:
        pass
    iters = int(pre.get("KdfIterations") or profile.get("kdfIterations") or 600000)
    master = hashlib.pbkdf2_hmac("sha256", secret("VAULTWARDEN__MASTERPASSWORD").encode(),
                                 email.encode(), iters, 32)
    for enc_key, mac_key in ((hkdf_expand(master, b"enc", 32), hkdf_expand(master, b"mac", 32)),
                             (master, None)):
        got = dec(profile.get("key"), enc_key, mac_key)
        if got and len(got) in (32, 64):
            return got
    raise SystemExit("could not derive the Vaultwarden user key")


def mikrotik_credential():
    req = urllib.request.Request(BASE + "/api/sync?excludeDomains=true")
    req.add_header("Authorization", "Bearer " + vw_token())
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.load(r)
    uk = user_key(data.get("profile") or {})
    enc, mac = uk[:32], uk[32:]
    org_keys = {}
    for org in data.get("organizations") or []:
        key = dec(org.get("key"), enc, mac)
        if key:
            org_keys[org["id"]] = key[:32]
    for cipher in data.get("ciphers") or []:
        if cipher.get("deletedDate"):
            continue
        key = uk[:32] if not cipher.get("organizationId") else org_keys.get(cipher["organizationId"])
        if not key:
            continue
        login = cipher.get("login") or {}
        blob = " ".join([
            to_str(dec(cipher.get("name"), key, mac)) or "",
            to_str(dec(cipher.get("notes"), key, mac)) or "",
            " ".join((u or {}).get("uri") or "" for u in login.get("uris") or []),
        ])
        if not re.search(r"mikrotik|routeros|hEX|hAP|\b88\.1\b", blob, re.I):
            continue
        user = to_str(dec(login.get("username"), key, mac))
        passwd = to_str(dec(login.get("password"), key, mac))
        if user and passwd:
            return user, passwd
    raise SystemExit("no usable MikroTik login found in the personal vault")


def rest(auth, path, method="GET", payload=None):
    req = urllib.request.Request(
        MIKROTIK.rstrip("/") + path,
        data=json.dumps(payload).encode() if payload is not None else None,
        method=method)
    req.add_header("Authorization", "Basic " + auth)
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            body = r.read().decode(errors="replace")
            return json.loads(body) if body.strip().startswith(("[", "{")) else body
    except urllib.error.HTTPError as e:
        raise SystemExit("routeros %s %s -> HTTP %s %s" % (
            method, path, e.code, e.read(200).decode(errors="replace")))


def desired():
    want = {}
    for line in (HERE / "records.txt").read_text().splitlines():
        parts = line.split()
        if len(parts) == 2 and not parts[0].startswith("#"):
            want[parts[0]] = parts[1]
    return want


def main():
    apply = "--apply" in sys.argv
    want = desired()
    auth = base64.b64encode(("%s:%s" % mikrotik_credential()).encode()).decode()
    current = {r["name"]: r for r in rest(auth, "/rest/ip/dns/static") if isinstance(r, dict)}

    if "--list" in sys.argv:
        for name in sorted(current):
            r = current[name]
            print("%-40s %-6s %-28s %s" % (name, r.get("type", "A"),
                                           r.get("cname") or r.get("address") or "",
                                           r.get(".id")))
        return

    create, update, prune = [], [], []
    for name, target in sorted(want.items()):
        have = current.get(name)
        if not have:
            create.append((name, target))
        elif have.get("type") != "CNAME" or have.get("cname") != target:
            update.append((name, target, have[".id"]))
    # extras are only reported: records pointing at LAN hosts (rd, internal
    # services that left the istio gateway) are not this script's to delete.
    # --prune removes them explicitly.
    for name, have in sorted(current.items()):
        if name.endswith(".lag0.com.br") and name not in want and have.get("dynamic") != "true":
            prune.append((name, have.get("cname") or have.get("address") or "", have[".id"]))

    print("desired=%d current=%d" % (len(want), len(current)))
    for name, target in create:
        print("  + %-40s %s" % (name, target))
    for name, target, _ in update:
        print("  ~ %-40s -> %s" % (name, target))
    for name, target, _ in prune:
        print("  ? %-40s fora do records.txt (atual %s)" % (name, target))
    for name, have in sorted(current.items()):
        if name.endswith(".lag0.com.br") and name not in want and have.get("dynamic") == "true":
            print("  = %-40s registro dinamico (licenca/dhcp), ignorado" % name)
    if not (create or update):
        print("\nrouter already matches records.txt")
        return
    if not apply:
        print("\ndry-run: re-run with --apply to write")
        return

    for name, target in create:
        rest(auth, "/rest/ip/dns/static", "PUT",
             {"name": name, "type": "CNAME", "cname": target, "ttl": "1h"})
        print("created", name)
    for name, target, rid in update:
        rest(auth, "/rest/ip/dns/static/" + rid, "PATCH",
             {"type": "CNAME", "cname": target, "ttl": "1h"})
        print("updated", name)
    if "--prune" in sys.argv:
        for name, _, rid in prune:
            rest(auth, "/rest/ip/dns/static/" + rid, "DELETE")
            print("pruned", name)
    print("cache flush:", rest(auth, "/rest/ip/dns/cache/flush", "POST"))


main()
